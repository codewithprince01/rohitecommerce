/** Convert ZeptoProductItem to full ProductWithVariants for cart and detail support */
export function convertToProductWithVariants(item: ZeptoProductItem): ProductWithVariants {
  const variantId = `${item.id}-var-default`;
  return {
    id: item.id,
    name: item.name,
    slug: item.slug,
    description: `${item.name} - ${item.weight}`,
    image: item.image,
    brand_id: 'brand-zepto',
    category_id: item.category_slug,
    subcategory_id: item.category_slug,
    is_available: true,
    tags: item.tag ? [item.tag] : [],
    created_at: new Date().toISOString(),
    variants: [
      {
        id: variantId,
        product_id: item.id,
        quantity: item.weight,
        price: item.price,
        original_price: item.original_price,
        discount: Math.round(((item.original_price - item.price) / item.original_price) * 100),
        stock: 50,
        is_available: true,
        created_at: new Date().toISOString(),
      },
    ],
    brand: item.brand_name ? {
      id: 'brand-zepto',
      name: item.brand_name,
      slug: item.brand_name.toLowerCase().replace(/[^a-z0-9]+/g, '-'),
      logo: null,
      description: null,
      subcategory_id: item.category_slug,
      created_at: new Date().toISOString(),
    } : undefined,
  };
}
